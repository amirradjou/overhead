-- One row per pass, the same model as analysis/src/overhead_stats/passes.sql, in Snowflake's dialect. Events are
-- counted once even if a batch was loaded twice. HOME_LAT/HOME_LON: the centre of the circle.
SET (HOME_LAT, HOME_LON) = (43.6777, -79.6248);

CREATE OR REPLACE VIEW OVERHEAD.ANALYTICS.POSITIONS AS
SELECT * FROM OVERHEAD.RAW.POSITIONS
QUALIFY ROW_NUMBER() OVER (PARTITION BY RUN, SEQ ORDER BY LOADED) = 1;

CREATE OR REPLACE VIEW OVERHEAD.ANALYTICS.PASSES AS
WITH MARKED AS (
    SELECT *,
        IFF(LAG(AT) OVER (PARTITION BY HEX ORDER BY AT) IS NULL
            OR DATEDIFF('second', LAG(AT) OVER (PARTITION BY HEX ORDER BY AT), AT) > 600, 1, 0) AS STARTS_PASS
    FROM OVERHEAD.ANALYTICS.POSITIONS
), NUMBERED AS (
    SELECT *,
        SUM(STARTS_PASS) OVER (PARTITION BY HEX ORDER BY AT ROWS UNBOUNDED PRECEDING) AS PASS,
        HAVERSINE($HOME_LAT, $HOME_LON, LAT, LON) AS DISTANCE_KM
    FROM MARKED
)
SELECT HEX, PASS,
    MIN(AT) AS FIRST_SEEN, MAX(AT) AS LAST_SEEN,
    MODE(CALLSIGN) AS CALLSIGN, MODE(REGISTRATION) AS REGISTRATION, MODE(TYPE_CODE) AS TYPE_CODE,
    MIN(DISTANCE_KM) AS CLOSEST_KM,
    MIN(IFF(ON_GROUND, NULL, ALT_FT)) AS LOWEST_ALT_FT,
    BOOLOR_AGG(ON_GROUND) AS ON_GROUND_AT_SOME_POINT,
    BOOLOR_AGG(MILITARY) AS MILITARY, BOOLOR_AGG(PRIVATE) AS PRIVATE,
    COUNT(*) AS POSITIONS
FROM NUMBERED
GROUP BY HEX, PASS;
